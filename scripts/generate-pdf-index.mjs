import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import * as mupdf from 'mupdf'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const PDF_DIR = path.resolve(__dirname, '../public/pdfs/stories')
const COVERS_DIR = path.resolve(__dirname, '../public/images/covers')
const MOVIES_DIR = path.resolve(__dirname, '../public/movies')
const OUTPUT_FILE = path.resolve(__dirname, '../src/data/generated-stories.ts')

function slugToTitle(slug) {
  return slug
    .split(/[-_]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

function parsePdfFilename(filename) {
  const basename = filename.replace(/\.pdf$/i, '')
  const date = basename.slice(0, 10)
  const slug = basename.slice(11)
  const title = slugToTitle(slug)
  return { date, slug, title }
}

function hasManualCover(slug, date) {
  const base = `${date}-${slug}`
  const extensions = ['.png', '.jpg', '.jpeg', '.webp']

  for (const ext of extensions) {
    const coverPath = path.join(COVERS_DIR, base + ext)
    if (fs.existsSync(coverPath)) {
      return `/images/covers/${base}${ext}`
    }
  }
  return null
}

function extractCoverFromPdf(pdfPath, outputPath) {
  const fileBuffer = fs.readFileSync(pdfPath)
  const doc = mupdf.Document.openDocument(fileBuffer, 'application/pdf')
  const page = doc.loadPage(0)

  const bounds = page.getBounds()
  const width = bounds[2] - bounds[0]

  const scale = 800 / width
  const matrix = mupdf.Matrix.scale(scale, scale)

  const pixmap = page.toPixmap(matrix, mupdf.ColorSpace.DeviceRGB, false, true)
  const pngBuffer = pixmap.asPNG()

  fs.writeFileSync(outputPath, pngBuffer)
}

function extractTextFromPdf(pdfPath) {
  const fileBuffer = fs.readFileSync(pdfPath)
  const doc = mupdf.Document.openDocument(fileBuffer, 'application/pdf')
  const pageCount = doc.countPages()
  const lines = []

  for (let i = 0; i < pageCount; i++) {
    const page = doc.loadPage(i)
    const text = page.toStructuredText('preserve-whitespace').asText()
    const pageLines = text
      .split('\n')
      .map((l) => l.trim())
      .filter((l) => l.length > 0)
    lines.push(...pageLines)
  }

  return lines
}

function buildAnimationMap() {
  if (!fs.existsSync(MOVIES_DIR)) {
    return new Map()
  }
  const map = new Map()
  const files = fs.readdirSync(MOVIES_DIR).filter((f) => f.toLowerCase().endsWith('.html'))
  for (const filename of files) {
    const basename = filename.replace(/\.html$/i, '')
    const dateSlug = basename
    map.set(dateSlug, `/movies/${filename}`)
  }
  return map
}

function generate() {
  if (!fs.existsSync(PDF_DIR)) {
    fs.mkdirSync(PDF_DIR, { recursive: true })
  }
  if (!fs.existsSync(COVERS_DIR)) {
    fs.mkdirSync(COVERS_DIR, { recursive: true })
  }

  const animationMap = buildAnimationMap()

  const files = fs
    .readdirSync(PDF_DIR)
    .filter((f) => f.toLowerCase().endsWith('.pdf'))
    .sort()
    .reverse()

  const stories = []

  for (let index = 0; index < files.length; index++) {
    const filename = files[index]
    const { date, slug, title } = parsePdfFilename(filename)
    const pdfUrl = `/pdfs/stories/${filename}`

    let coverImage = hasManualCover(slug, date)

    if (!coverImage) {
      const generatedFilename = `${date}-${slug}.png`
      const generatedPath = path.join(COVERS_DIR, generatedFilename)

      if (!fs.existsSync(generatedPath)) {
        try {
          const pdfPath = path.join(PDF_DIR, filename)
          extractCoverFromPdf(pdfPath, generatedPath)
          console.log(`  📸 Generated cover: ${generatedFilename}`)
        } catch (err) {
          console.warn(`  ⚠️  Failed to extract cover from ${filename}:`, err.message)
        }
      }

      if (fs.existsSync(generatedPath)) {
        coverImage = `/images/covers/${generatedFilename}`
      } else {
        coverImage = '/images/covers/default-cover.svg'
      }
    }

    const dateSlug = `${date}-${slug}`
    const animationUrl = animationMap.get(dateSlug) || undefined

    if (animationUrl) {
      console.log(`  🎬 Matched animation: ${dateSlug}.html`)
    }

    let pdfText = []
    try {
      const pdfPath = path.join(PDF_DIR, filename)
      pdfText = extractTextFromPdf(pdfPath)
      if (pdfText.length > 0) {
        console.log(`  📝 Extracted ${pdfText.length} lines of text from ${filename}`)
      }
    } catch (err) {
      console.warn(`  ⚠️  Failed to extract text from ${filename}:`, err.message)
    }

    stories.push({
      id: `pdf-${index + 1}`,
      slug,
      title,
      date,
      category: 'english-book',
      tags: ['英文绘本', '亲子阅读'],
      ageRange: '4-8岁',
      duration: '8分钟',
      coverImage,
      pdfUrl,
      animationUrl,
      pdfText: pdfText.length > 0 ? pdfText : undefined,
      description: `今天和优米Leo一起阅读《${title}》，每天15分钟，讲故事、读绘本、看世界。`,
    })
  }

  const output = `// This file is auto-generated by scripts/generate-pdf-index.mjs
// Do not edit manually. Run: npm run generate:stories

export type StoryCategory =
  | 'english-book'
  | 'chinese-story'
  | 'world-culture'
  | 'music'
  | 'daily-life'

export type Story = {
  id: string
  slug: string
  title: string
  date: string
  category: StoryCategory
  tags: string[]
  ageRange: string
  duration: string
  coverImage: string
  pdfUrl: string
  animationUrl?: string
  pdfText?: string[]
  description: string
  goal?: string
  vocabulary?: {
    word: string
    meaning: string
    example?: string
  }[]
  parentQuestions?: string[]
}

export const generatedStories: Story[] = ${JSON.stringify(stories, null, 2)}
`

  const outputDir = path.dirname(OUTPUT_FILE)
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true })
  }

  fs.writeFileSync(OUTPUT_FILE, output, 'utf-8')
  console.log(`✅ Generated ${stories.length} stories → ${OUTPUT_FILE}`)
}

generate()
